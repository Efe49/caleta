export function getZone(id: string): Zone {
  return ZONES.find((zone) => zone.id === id) ?? ZONES[0];
}

export function getRod(id: string): Rod {
  return RODS.find((rod) => rod.id === id) ?? RODS[0];
}

export function getReel(id: string): Reel {
  return REELS.find((reel) => reel.id === id) ?? REELS[0];
}

export function getBait(id: string): Bait {
  return BAITS.find((bait) => bait.id === id) ?? BAITS[0];
}

export function getFish(id: string): Fish | undefined {
  return FISH.find((fish) => fish.id === id);
}
